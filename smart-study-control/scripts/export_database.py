"""Export schema documentation and PostgreSQL DDL from actual SQLAlchemy metadata."""
from pathlib import Path
import sys
from sqlalchemy.schema import CreateTable, CreateIndex
from sqlalchemy.dialects import postgresql

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'backend'))
from app.db.session import Base  # noqa: E402
from app.models import entities  # noqa: E402, F401

metadata = Base.metadata
dialect = postgresql.dialect()
intro = f'''# Database schema

{len(metadata.tables)} ORM tables. Static Alembic migrations are authoritative for deployment. This document and `postgresql-schema.sql` are generated by `scripts/export_database.py`; neither executes migrations. Run `alembic upgrade head` and `alembic check` against the target database. PostgreSQL is the deployment target; SQLite was used for local tests.

Timestamps are UTC. Typed timestamp responses use Z; untyped reading detail responses may omit the suffix and must still be interpreted as UTC. Parent links and current classroom membership scope reading plans. Source hashes and lesson versions bind publication and attempt snapshots. Wallet locks and unique transaction origins serialize credit/spend writes. Reading credit is unique per learner and lesson, independent of repeated plan creation. Automation settings are per child and authorized by a linked guardian; runs are unique per child/local day.

Migration order: initial schema → seeded roles → reading/autopilot tables. Room on Android separately migrates v1→v2 without deleting the existing assignment cache or submission outbox.
'''
sections = [intro]
ddl = ['-- Generated PostgreSQL schema reference; deploy with Alembic, not this file.\n']
for table in metadata.sorted_tables:
    lines = [f'\n## {table.name}\n', '| Column | Type | Nullable | References |', '|---|---|---|---|']
    for c in table.columns:
        refs = ', '.join(sorted(fk.target_fullname for fk in c.foreign_keys))
        lines.append(f'| {c.name}{" (PK)" if c.primary_key else ""} | {c.type} | {c.nullable} | {refs} |')
    lines.append('\nIndexes: ' + (', '.join(sorted(index.name for index in table.indexes)) or 'none') + '.')
    constraints = [str(constraint.sqltext) for constraint in table.constraints if hasattr(constraint, 'sqltext')]
    if constraints:
        lines.append('\nChecks: ' + '; '.join(constraints) + '.')
    sections.append('\n'.join(lines))
    ddl.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ';\n')
    ddl.extend(str(CreateIndex(index).compile(dialect=dialect)) + ';\n' for index in sorted(table.indexes, key=lambda i: i.name))
(root / 'docs/DATABASE.md').write_text('\n'.join(sections) + '\n')
(root / 'docs/postgresql-schema.sql').write_text('\n'.join(ddl))
print(f'{len(metadata.tables)} tables exported')
